#!/usr/bin/env python3
"""Author deterministic layouts. JSON is the reviewable source; .inc is its bundled mirror."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
levels=[]
shapes=['Twin Wings','Center Bridge','Side Entry','Deep Notch','Stair Steps','Split Canopy']
for index in range(30):
    lid=index+1; shape=index%6; chapter=index//5
    kind=['clear','collect','fall','survive','clear'][index%5]
    depth=(7 if kind=='survive' else 5+chapter//2 if kind=='fall' else 4+chapter//2+(shape in (1,4))); waves=2 if kind in ('fall','collect') or (kind=='clear' and chapter>=2) else 1
    layouts=[]
    for wave in range(waves):
        rows=[]
        for r in range(depth):
            n=17 if r%2 else 18
            cells=[]
            for c in range(n):
                on=True
                if r>=2:
                    if shape==0: on=not(7<=c<=9 and r>=depth-2)
                    elif shape==1: on=(5<=c<=11) if r==2 else (2<=c<=14)
                    elif shape==2: on=c>=min(4,r) if (chapter+(wave if kind not in ('clear','collect') else 0))%2==0 else c<n-min(4,r)
                    elif shape==3: on=not(6<=c<=10 and r>=3)
                    elif shape==4: on=r<=2+(c+chapter)%6
                    elif shape==5: on=not(4<=c<=5 or 11<=c<=12) if r>=3 else True
                # Connected same-colour horizontal groups, while bridges carry contrasting colours.
                color=((c//(3+chapter%2))+(r//2)+chapter+wave)%4
                if kind=='fall':
                    # Five independent suspended two-column piers. Exposed coloured supports
                    # differ from their payload, so cutting supports produces actual falls.
                    k=17-c if wave%2 else c
                    structure=chapter%3
                    if structure==0:
                        on=k%4 in ((1,2) if wave%2 else (0,1))
                        color=((k//4)+chapter)%4 if r<=(2 if lid in (8,13) else 1) else ((k//4)+chapter+1+r//2)%4
                    elif structure==1:
                        on=any(a<=k<=b for a,b in ([(0,2),(7,9),(14,16)] if r<=1 else [(0,4),(6,10),(12,16)]))
                        color=((k//6)+chapter)%4 if r<=(2 if lid in (8,13) else 1) else ((k//6)+chapter+1+r//2)%4
                    else:
                        on=any(a<=k<=b for a,b in ([(2,3),(8,9),(14,15)] if r<=1 else [(2,15)] if r==2 else [(2,6),(8,12),(14,16)]))
                        color=((k//6)+chapter)%4 if r<=(2 if lid in (8,13) else 1) else ((k//4)+chapter+1+r//2)%4
                if kind!='fall' and shape==1 and r==2: color=(chapter+wave)%4
                if lid==27 and wave==1 and r<=1 and c<3: color=(chapter+shape)%4
                if kind=='clear' and chapter>=2: color=((c//(6 if lid in (11,15,25) else 3+chapter%2))+chapter+wave)%4
                cells.append(str(color) if on else '.')
            rows.append(''.join(cells)[::-1] if wave%2 and kind in ('clear','collect') else ''.join(cells))
        layouts.append(rows)
    payload=sum(ch!='.' for rows in layouts[:1] for row in rows[2:] for ch in row)
    target=36 if lid==28 else 40 if lid in (8,23) else (payload+3) if kind=='fall' and chapter%3==1 else waves if kind=='clear' else (20+chapter*5 if kind=='collect' else 28+chapter*4 if kind=='fall' else 58+chapter*7)
    levels.append(dict(id=lid,title=(['Suspended Piers','Wing Supports','Forked Bridge'][chapter%3] if kind=='fall' else shapes[shape]),objective=kind,color=(chapter+shape)%4,target=target,
                       pressureInterval=round((12-chapter*.65) if kind=='survive' else 26 if lid==1 else 20-chapter*1.2-(shape%3)*.5,1),parShots=((58+chapter*7+1)//2+2 if kind=='survive' else 12+chapter*2+(waves-1)*6),
                       parTime=35+chapter*6+(waves-1)*25,parScore=1000+chapter*200 if kind=='survive' else 0,seed=20261000+lid,layouts=layouts,startingEnergy=[0,0,0,0]))
raw=json.dumps({'format':1,'levels':levels},indent=2)+'\n'
(root/'Resources/Data/levels.json').write_text(raw)
compact=json.dumps(json.loads(raw),separators=(',',':'))
(root/'Sources/Core/GDLevelsData.inc').write_text('// Generated by scripts/generate_levels.py from the level design.\n@'+json.dumps(compact)+'\n')
